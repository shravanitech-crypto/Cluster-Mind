const aliasIndex = giftRecipients.reduce((acc, item) => {
  acc[item.key] = item.key
  acc[item.label.toLowerCase()] = item.key
  item.aliases.forEach((alias) => {
    acc[alias.toLowerCase()] = item.key
  })
  return acc
}, {})

export const resolveRecipientKey = (value) => {
  if (!value) return ''
  const normalised = String(value).trim().toLowerCase().replace(/[_]+/g, ' ').replace(/\s+/g, ' ')
  if (!normalised) return ''
  if (aliasIndex[normalised]) return aliasIndex[normalised]
  const collapsed = normalised.replace(/[^a-z]/g, '')
  if (aliasIndex[collapsed]) return aliasIndex[collapsed]
  for (const item of giftRecipients) {
    if (normalised.includes(item.key) || item.aliases.some((alias) => normalised.includes(alias))) {
      return item.key
    }
  }
  return ''
}

export const matchesGiftRecipient = (product, recipientKey) => {
  const key = resolveRecipientKey(recipientKey)
  if (!key) return true
  const recipient = giftRecipients.find((item) => item.key === key)
  if (!recipient) return true
  if (Array.isArray(product.giftTags) && product.giftTags.length) {
    return product.giftTags.some((tag) => resolveRecipientKey(tag) === key)
  }
  const haystack = `${product.name || ''} ${product.category || ''} ${product.brand || ''} ${product.description || ''}`.toLowerCase()
  return (
    recipient.categories.includes(product.category) ||
    recipient.keywords.some((word) => haystack.includes(word))
  )
}

export const scoreGiftMatch = (product, recipientKey) => {
  const key = resolveRecipientKey(recipientKey)
  if (!key || !product) return 0
  const recipient = giftRecipients.find((item) => item.key === key)
  if (!recipient) return 0
  let score = 0
  if (Array.isArray(product.giftTags) && product.giftTags.some((tag) => resolveRecipientKey(tag) === key)) {
    score += 100
  }
  if (recipient.categories.includes(product.category)) score += 50
  const haystack = `${product.name || ''} ${product.category || ''} ${product.brand || ''} ${product.description || ''}`.toLowerCase()
  score += recipient.keywords.filter((word) => haystack.includes(word)).length * 10
  score += Number(product.rating || 0) * 2
  if (Number(product.stock || 0) > 0) score += 5
  return score
}

export const rankGiftsForRecipient = (products = [], recipientKey, limit = 6) =>
  [...products]
    .filter((product) => matchesGiftRecipient(product, recipientKey))
    .sort((a, b) => scoreGiftMatch(b, recipientKey) - scoreGiftMatch(a, recipientKey))
    .slice(0, limit)
